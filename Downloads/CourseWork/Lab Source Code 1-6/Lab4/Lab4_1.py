print("Comparing two numbers:")
f1 = float(input('  Enter 1st Float number: '))
f2 = float(input('  Enter 2nd Float number: '))
print(f"  The entered numbers are {f1:.1f} and {f2:.1f}")
if f1==f2:
    print (f1, "equals", f2)
elif f1>f2:
    print (f1, "is greater than", f2)
else:
    print (f1, "is less than", f2)

